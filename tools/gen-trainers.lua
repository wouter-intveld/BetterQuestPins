-- Generates Trainers.lua: which profession each trainer NPC teaches, and which
-- class-specific trainers have no class name in their subtitle (portal trainers).
-- Evaluates Questie's own trainer lists for Forever.
--
--   lua5.1 tools/gen-trainers.lua ../Questie > Trainers.lua

local questie = assert(arg[1], "path to the Questie addon folder")

-- Questie's profession keys, as the game's skill line IDs.
local SKILL = {
    ALCHEMY = 171, BLACKSMITHING = 164, COOKING = 185, ENCHANTING = 333, ENGINEERING = 202,
    FIRST_AID = 129, FISHING = 356, HERBALISM = 182, LEATHERWORKING = 165, MINING = 186,
    SKINNING = 393, TAILORING = 197, JEWELCRAFTING = 755, INSCRIPTION = 773, ARCHAEOLOGY = 794,
}

local professionOf = {}
local Townsfolk = {
    SetProfessionTrainerIds = function(key, ids)
        local skill = SKILL[key]
        if not skill then return end -- riding is not a profession
        for _, id in ipairs(ids or {}) do professionOf[id] = skill end
    end,
}
local keys = setmetatable({}, { __index = function(_, k) return k end })
local modules = { Townsfolk = Townsfolk, QuestieProfessions = { professionKeys = keys } }
QuestieLoader = { ImportModule = function(_, name) return modules[name] or {} end }
Questie = setmetatable({ IsForever = true }, { __index = function() return false end })

local dir = questie .. "/Modules/QuestieMenu/ProfessionTrainers/"
local files = assert(io.popen(('ls "%s"'):format(dir)))
for file in files:lines() do
    if file:match("%.lua$") then assert(loadfile(dir .. file))() end
end
files:close()

-- Portal trainers: Questie keeps them with its class townsfolk.
local portal = {}
local townsfolk = assert(io.open(questie .. "/Modules/QuestieMenu/Townsfolk.lua")):read("*a")
local list = townsfolk:match('%["MAGE"%]%["Portal Trainer"%]%s*=%s*(%b{})')
for id in (list or ""):gmatch("%d+") do portal[#portal + 1] = tonumber(id) end

local ids = {}
for id in pairs(professionOf) do ids[#ids + 1] = id end
table.sort(ids)
table.sort(portal)

io.write("-- Generated by tools/gen-trainers.lua from Questie's trainer lists; do not edit by hand.\n")
io.write("-- Source: Questie (https://github.com/Questie/Questie), used under the GPLv3.\n")
io.write("local _, ns = ...\n")
io.write("-- npcID = skill line ID of the profession it teaches\n")
io.write("ns.TRAINER_PROFESSION = {\n")
for _, id in ipairs(ids) do io.write(("    [%d] = %d,\n"):format(id, professionOf[id])) end
io.write("}\n")
io.write("-- Class trainers whose subtitle names no class\n")
io.write("ns.CLASS_TRAINER = {\n")
for _, id in ipairs(portal) do io.write(("    [%d] = \"MAGE\",\n"):format(id)) end
io.write("}\n")
io.stderr:write(("%d profession trainers, %d portal trainers\n"):format(#ids, #portal))
