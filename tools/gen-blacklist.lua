-- Generates Blacklist.lua: quest IDs Questie hides because they exist in the
-- data but cannot be taken in game. Evaluates Questie's own list for Forever,
-- which Questie treats as Era content.
--
--   lua5.1 tools/gen-blacklist.lua ../Questie/Database/Corrections/QuestieQuestBlacklist.lua > Blacklist.lua

local source = assert(arg[1], "path to QuestieQuestBlacklist.lua")

-- Anything the list asks about that we don't model answers "no".
local function stub()
    return setmetatable({}, {
        __index = function() return false end,
        __call = function() return {} end,
    })
end

local Expansions = { Era = 1, Tbc = 2, Wotlk = 3, Cata = 4, MoP = 5, Mop = 5, Current = 1 }
local ContentPhases = setmetatable({ activePhases = stub() }, {
    __index = function() return function() return {} end end,
})
local modules = { Expansions = Expansions, ContentPhases = ContentPhases }
QuestieLoader = {
    CreateModule = function(_, name) modules[name] = modules[name] or {} return modules[name] end,
    ImportModule = function(_, name) return modules[name] or stub() end,
}
Questie = stub()

assert(loadfile(source))()
local list = modules.QuestieQuestBlacklist:Load()

local ids = {}
for id, flag in pairs(list) do
    if flag then ids[#ids + 1] = id end -- true, or "HIDE_ON_MAP": hidden on the map either way
end
table.sort(ids)

io.write("-- Generated by tools/gen-blacklist.lua from Questie's quest blacklist; do not edit by hand.\n")
io.write("-- Quest IDs that exist in the data but cannot be picked up in game.\n")
io.write("-- Source: Questie (https://github.com/Questie/Questie), used under the GPLv3.\n")
io.write("local _, ns = ...\nns.BLACKLIST = {\n")
for _, id in ipairs(ids) do io.write(("    [%d] = true,\n"):format(id)) end
io.write("}\n")
io.stderr:write(("%d quest IDs\n"):format(#ids))
